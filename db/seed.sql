UPDATE teams
   SET semester_cohort = CASE
     WHEN group_type = 'ADV' THEN COALESCE(
       (SELECT c.cohort FROM cohorts c WHERE c.adv_term = teams.cohort),
       (SELECT cohort FROM cohorts WHERE is_current = 1)
     )
     ELSE cohort
   END;

